'use strict';
const assert=require('node:assert/strict');
const {createDirectory}=require('../source/daily-report-memberships');
const {createSessionStore}=require('../source/daily-report-session-store');
const d=createDirectory();
d.grant({userId:'u',companyId:'a',projectId:'p1',role:'foreman'});
d.grant({userId:'u',companyId:'a',projectId:'p2',role:'accounting'});
d.grant({userId:'v',companyId:'b',projectId:'p1',role:'foreman'});
assert.equal(d.resolve('u','a','p1','foreman').projectId,'p1');
assert.equal(d.resolve('u','a','p2','accounting').role,'accounting');
assert.equal(d.resolve('u','a','p2','foreman'),null);
assert.equal(d.resolve('u','b','p1','foreman'),null);
assert.throws(()=>d.grant({userId:'u',companyId:'a',projectId:'p1',role:'foreman'}),/Duplicate/);
assert.throws(()=>d.grant({userId:'u',companyId:'a',projectId:'p3',role:'root'}),/Invalid/);
const sessions=createSessionStore();
const token=sessions.issue({id:'u',role:'foreman',companyId:'a',projectId:'p1'});
assert.equal(d.resolve(sessions.resolve(token).id,'a','p1','foreman').role,'foreman');
d.revoke({userId:'u',companyId:'a',projectId:'p1',role:'foreman'});
assert.equal(d.resolve(sessions.resolve(token).id,'a','p1','foreman'),null);
assert.equal(d.resolve('u','a','p2','accounting').role,'accounting');
console.log('PASS: tenant membership, project isolation, least privilege and grant revocation');
