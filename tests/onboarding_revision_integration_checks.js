'use strict';
const assert=require('node:assert/strict');
const lifecycle=require('../source/safety-revision-lifecycle');
const workflow=require('../source/onboarding-workflow');
const safety={id:'safety',companyId:'demo',role:'safety-admin'};
const employee={id:'worker',companyId:'demo',role:'employee'};
const foreman={id:'foreman',companyId:'demo',role:'foreman'};
const foreign={...employee,companyId:'other'};
const source={id:'orientation-1',companyId:'demo',title:'Site orientation',content:'Fictional muster point',type:'ORIENTATION',roles:['employee']};
const draft=lifecycle.ingest(source,safety);
assert.throws(()=>lifecycle.assignment(draft),/Draft/);
let published=lifecycle.publish(draft,safety);
let docs=[lifecycle.assignment(published)];
let records=[];
let pkg=workflow.packageFor(docs,employee,records);
assert.equal(pkg.total,1);assert.equal(pkg.completed,0);
records=workflow.submitAcknowledgement(docs,employee,{documentId:'orientation-1',revision:'1',reviewed:true,acknowledgedAt:'2026-11-13T12:00:00.000Z'},records);
assert.equal(workflow.packageFor(docs,employee,records).completed,1);
assert.equal(workflow.packageFor(docs,foreign,records).total,0);
assert.deepEqual(workflow.roleView(safety,[employee,foreign],docs,records).map(x=>x.employeeId),['worker']);
const revised=lifecycle.revise(published,safety,'Fictional updated muster point');
assert.throws(()=>lifecycle.assignment(revised),/Draft/);
assert.equal(workflow.packageFor(docs,employee,records).completed,1,'Existing approved revision stays effective while draft awaits approval');
published=lifecycle.publish(revised,safety);docs=[lifecycle.assignment(published)];
pkg=workflow.packageFor(docs,employee,records);
assert.equal(pkg.total,1);assert.equal(pkg.completed,0,'Revision 1 acknowledgement must not satisfy revision 2');
assert.throws(()=>workflow.submitAcknowledgement(docs,employee,{documentId:'orientation-1',revision:'1',reviewed:true,acknowledgedAt:'2026-11-13T12:00:00.000Z'},records),/outdated/);
records=workflow.submitAcknowledgement(docs,employee,{documentId:'orientation-1',revision:'2',reviewed:true,acknowledgedAt:'2026-11-13T12:01:00.000Z'},records);
assert.equal(workflow.packageFor(docs,employee,records).completed,1);
assert.equal(records.length,2,'Prior revision acknowledgement retained as history');
const flha={id:'flha-1',companyId:'demo',foremanId:'foreman',revision:'3',status:'submitted'};
const decision=workflow.flhaReview(flha,foreman,{status:'returned',reason:'Clarify controls',reviewedAt:'2026-11-13T12:02:00.000Z'});
assert.equal(lifecycle.reviewStatus(flha,decision).reviewedRevision,'3');
assert.throws(()=>lifecycle.reviewStatus({...flha,revision:'4'},decision),/mismatch/);
assert.throws(()=>workflow.flhaReview(flha,{...foreman,id:'other'}, {status:'approved',reviewedAt:'2026-11-13T12:02:00.000Z'}),/not assigned/);
console.log('PASS: integrated fictional draft-to-approval-to-reacknowledgement and FLHA revision checks');
