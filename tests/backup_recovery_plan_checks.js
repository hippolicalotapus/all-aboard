'use strict';
const assert=require('node:assert/strict');
const planner=require('../source/backup-recovery-plan.js');
const workflow=require('../source/workflow-store.js');
const review=require('../source/task-review.js');
const model=require('../source/workflow-model.js');
const old={format:workflow.FORMAT,plans:[{kind:'onboarding',role:'field',site:'jobsite',completed:['start']}]};
const empty=workflow.empty();
const current={workflow:old,review:review.empty()};
const before=JSON.stringify(current);
const result=planner.plan({workflow:empty},current,workflow,review,model);
assert.equal(result.safeToRestore,true);
assert.deepEqual(result.sections.workflow,{present:true,existing:1,incoming:0,delta:-1,willReplace:true});
assert.equal(result.sections.review.present,false);
assert.equal(result.writes,false);
assert.equal(JSON.stringify(current),before);
assert.equal(planner.plan({},current,workflow,review,model).safeToRestore,false);
for(const raw of [null,[],42,'bad'])assert.equal(planner.plan(raw,current,workflow,review,model).safeToRestore,false);
const invalid=planner.plan({workflow:empty,review:{format:review.FORMAT,records:[{bad:true}]}},current,workflow,review,model);
assert.equal(invalid.safeToRestore,false);
assert.equal(invalid.sections.workflow.willReplace,false,'no partial restore recommendation');
assert.deepEqual(invalid.errors,['review: invalid recovery data']);
assert.equal(planner.plan({workflow:old},{workflow:empty},workflow,review,model).sections.workflow.delta,1);
console.log('V40 read-only recovery impact and V39 preservation checks passed');
