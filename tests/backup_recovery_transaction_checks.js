'use strict';
const assert=require('node:assert/strict');
const tx=require('../source/backup-recovery-transaction.js');
const workflow=require('../source/workflow-store.js'),review=require('../source/task-review.js'),model=require('../source/workflow-model.js');
const backup={format:workflow.FORMAT,plans:[{kind:'onboarding',role:'field',site:'jobsite',completed:['start']}]};
const notes={format:review.FORMAT,records:[]};
const stage={ready:true,replacements:{workflow:backup,review:notes}};
const original=new Map([[workflow.KEY,'original-workflow'],[review.KEY,'original-review'],['onboardflow-fictional-wallet-v2','wallet-untouched']]);
function storage(map,failKey){return {getItem:k=>map.has(k)?map.get(k):null,setItem(k,v){if(k===failKey)throw Error('simulated failure');map.set(k,v)},removeItem:k=>map.delete(k)}}
let map=new Map(original),store=storage(map);
assert.equal(tx.apply(stage,store,workflow,review,model,false).ok,false);
assert.deepEqual(map,original,'unconfirmed recovery must never write');
const success=tx.apply(stage,store,workflow,review,model,true);
assert.equal(success.ok,true);
assert.equal(JSON.parse(map.get(workflow.KEY)).plans.length,1);
assert.equal(map.get('onboardflow-fictional-wallet-v2'),'wallet-untouched');
map=new Map(original);store=storage(map,review.KEY);
const failure=tx.apply(stage,store,workflow,review,model,true);
assert.equal(failure.ok,false);
assert.equal(failure.rollbackVerified,false,'persistent write failure may prevent rollback');
assert.equal(map.get(workflow.KEY),'original-workflow');
assert.equal(map.get('onboardflow-fictional-wallet-v2'),'wallet-untouched');
map=new Map(original);
let failed=false;
store={getItem:k=>map.has(k)?map.get(k):null,setItem(k,v){if(k===review.KEY&&!failed){failed=true;throw Error('one-time failure')}map.set(k,v)},removeItem:k=>map.delete(k)};
const recovered=tx.apply(stage,store,workflow,review,model,true);
assert.equal(recovered.ok,false);
assert.equal(recovered.rollbackVerified,true);
assert.deepEqual(map,original,'one-time failure must restore both original sections');
assert.equal(tx.apply({ready:true,replacements:{workflow:{bad:true}}},storage(new Map(original)),workflow,review,model,true).writes,false);
console.log('V40 transactional recovery, explicit confirmation, wallet isolation and rollback verified');
