'use strict';
const assert=require('node:assert/strict'),m=require('../source/daily-report-lifecycle');
const ctx={companyId:'co',projectId:'site',date:'2026-11-13'};
const f={id:'f',role:'foreman',companyId:'co',projectId:'site'};
const verified={...ctx,id:'hours',kind:'time',quantity:8,unit:'hours',sourceId:'time-1',source:'time-entry',status:'verified'};
const planned={...ctx,id:'planned',kind:'material',quantity:50,unit:'units',sourceId:'flha-1',source:'flha-plan',status:'planned'};
let state=m.start([verified,planned],ctx);
assert.equal(state.report.exceptions.length,1);
assert.throws(()=>m.action(state,f,{type:'approve',actionId:'a'}),/Unresolved/);
assert.throws(()=>m.action(state,{...f,companyId:'other'},{type:'exclude',actionId:'b',recordId:'planned'}),/access denied/);
assert.throws(()=>m.action(state,f,{type:'correct',actionId:'c',recordId:'planned',quantity:5}),/Unverified/);
state=m.action(state,f,{type:'exclude',actionId:'exclude-plan',recordId:'planned'});
assert.equal(state.report.entries.length,1);
assert.strictEqual(m.action(state,f,{type:'exclude',actionId:'exclude-plan',recordId:'planned'}),state);
state=m.action(state,f,{type:'correct',actionId:'correct-hours',recordId:'hours',quantity:7});
assert.equal(state.report.entries[0].quantity,7);assert.equal(state.events[1].oldQuantity,8);
const superintendent={role:'superintendent',companyId:'co',projectIds:['site']};
assert.equal(m.view(state,superintendent).canEdit,false);
assert.throws(()=>m.view(state,{role:'accounting',companyId:'co',projectIds:['other']}),/access denied/);
assert.throws(()=>m.action(state,superintendent,{type:'approve',actionId:'bad'}),/access denied/);
state=m.action(state,f,{type:'approve',actionId:'approve-1'});
assert.equal(state.report.status,'foreman-approved');assert.equal(state.events.length,3);
assert.strictEqual(m.action(state,f,{type:'approve',actionId:'approve-1'}),state);
assert.throws(()=>m.action(state,f,{type:'correct',actionId:'after',recordId:'hours',quantity:6}),/immutable/);
assert(Object.isFrozen(state.events)&&Object.isFrozen(state.report));
assert.equal(m.view(state,{role:'accounting',companyId:'co',projectIds:['site']}).report.status,'foreman-approved');
console.log('PASS: lifecycle idempotency, source corrections, audit history, tenant isolation and approval');
