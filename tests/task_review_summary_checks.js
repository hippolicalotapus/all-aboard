'use strict';
const assert=require('node:assert/strict');
const review=require('../source/task-review.js');
const model=require('../source/workflow-model.js');
const blank=review.empty();
const summary=review.summarize(blank,model);
assert.equal(summary.total,0);
assert.equal(summary.evidenceLinks,0);
assert.equal(summary.missingEvidence,0);
assert.deepEqual(review.reviewAttention(blank,model),[]);
assert.equal(summary.employerApproval,false);
assert.deepEqual(summary.byStatus,{pending:0,reviewed:0,'changes-requested':0});
assert.deepEqual(blank,review.empty());
const record={kind:'onboarding',role:'field',site:'jobsite',taskId:'training',status:'changes-requested',note:'Fictional evidence required',evidenceUrl:''};
const input={format:review.FORMAT,records:[record]};
const original=JSON.stringify(input);
const attention=review.reviewAttention(input,model);
assert.deepEqual(attention,[{kind:'onboarding',role:'field',site:'jobsite',taskId:'training',needsEvidence:true,employerApproval:false}]);
assert.deepEqual(review.summarize(input,model),{total:1,byStatus:{pending:0,reviewed:0,'changes-requested':1},evidenceLinks:0,missingEvidence:1,employerApproval:false});
const linked={format:review.FORMAT,records:[{...record,evidenceUrl:'https://example.org/fictional-evidence'}]};
assert.deepEqual(review.reviewAttention(linked,model),[]);
assert.equal(review.summarize(linked,model).evidenceLinks,1);
assert.equal(review.summarize(linked,model).missingEvidence,0);
assert.equal(JSON.stringify(input),original,'read-only attention summary must not mutate backup');
console.log('V40 review summary and evidence transitions verified without V39 backup changes');
