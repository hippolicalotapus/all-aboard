'use strict';
const assert=require('node:assert/strict');
const auto=require('../source/daily-report-auto-drafts');
const lifecycle=require('../source/daily-report-lifecycle');
const base={companyId:'c1',projectId:'p1',date:'2026-11-15',kind:'time',quantity:8,unit:'hours',status:'verified',source:'timesheet'};
const a={...base,id:'time1',sourceId:'clock1'};
const b={...base,id:'time2',sourceId:'clock1',quantity:9};
const c={...base,id:'hours-next',date:'2026-11-16',sourceId:'clock2'};
const d={...base,id:'other-project',projectId:'p2',sourceId:'clock3'};
const foreign={...base,id:'other-tenant',companyId:'c2',sourceId:'clock4'};
const planned={...base,id:'plan1',sourceId:'plan1',source:'flha-plan',status:'planned'};
const input=[a,b,c,d,foreign,planned];const snapshot=JSON.stringify(input);
const reports=auto.generate(input,{companyId:'c1',projectIds:['p1','p2']});
assert.equal(reports.length,3);
const p1=reports.find(x=>x.context.projectId==='p1'&&x.context.date==='2026-11-15');
assert(p1);
assert.equal(p1.state.report.status,'draft');assert.equal(p1.state.report.requiresForemanApproval,true);
assert.deepEqual(p1.state.report.entries.map(x=>x.id),['time1']);
assert.deepEqual(p1.state.report.exceptions.map(x=>x.reason),['duplicate-source','not-verified-actual']);
assert.throws(()=>lifecycle.action(p1.state,{id:'foreman',role:'foreman',companyId:'c1',projectId:'p1'},{type:'approve',actionId:'a',expectedRevision:1}),/Unresolved exceptions/);
assert.equal(reports.some(x=>x.context.companyId==='c2'),false);
assert.equal(JSON.stringify(input),snapshot,'automatic draft generation may not modify entered records');
assert.deepEqual(auto.generate(input,{companyId:'c1',projectIds:['p1','p2']}).map(x=>x.context),reports.map(x=>x.context));
assert.throws(()=>auto.generate([{...a,id:' bad'}],{companyId:'c1',projectIds:['p1']}),/Invalid record id/);
assert.throws(()=>auto.generate([{...a,date:'2026-02-30'}],{companyId:'c1',projectIds:['p1']}),/Invalid source date/);
assert.throws(()=>auto.generate([{...a,sourceId:' bad'}],{companyId:'c1',projectIds:['p1']}),/Invalid source id/);
assert.throws(()=>auto.generate([a],{companyId:'c1',projectIds:['p1','p1']}),/Invalid generation scope/);
assert.deepEqual(auto.generate([foreign],{companyId:'c1',projectIds:['p1']}),[]);
console.log('PASS: automatic offline project/day draft grouping, exceptions, scope isolation and manual approval gate');
