'use strict';
const assert=require('node:assert/strict'),m=require('../source/safety-revision-lifecycle');
const admin={id:'safety',role:'safety-admin',companyId:'co-1'};
const input={id:'swp-1',companyId:'co-1',title:'Trenching',content:'Fictional procedure',type:'SWP',roles:['employee']};
const draft=m.ingest(input,admin);
assert.equal(draft.status,'draft');
assert.throws(()=>m.assignment(draft),/Draft/);
assert.throws(()=>m.ingest(input,{...admin,companyId:'co-2'}),/administrator/);
assert.throws(()=>m.ingest({...input,content:'x'.repeat(100001)},admin),/limit/);
const published=m.publish(draft,admin);
assert.equal(m.assignment(published).revision,'1');
const changed=m.revise(published,admin,'Fictional revised controls');
assert.equal(changed.revision,2);
assert.equal(changed.status,'draft');
assert.equal(changed.approvedBy,null);
assert.throws(()=>m.assignment(changed),/Draft/);
const republished=m.publish(changed,admin);
assert.equal(m.assignment(republished).revision,'2');
assert.equal(published.revision,1);
const flha={id:'f-1',companyId:'co-1',revision:'2',status:'submitted'};
const review={flhaId:'f-1',companyId:'co-1',revision:'2',foremanId:'foreman',status:'approved'};
assert.equal(m.reviewStatus(flha,review).reviewedRevision,'2');
assert.throws(()=>m.reviewStatus({...flha,revision:'3'},review),/mismatch/);
assert.throws(()=>m.reviewStatus(flha,{...review,companyId:'co-2'}),/mismatch/);
console.log('PASS: fictional ingestion validation, approval, revision, company isolation and FLHA review binding');
