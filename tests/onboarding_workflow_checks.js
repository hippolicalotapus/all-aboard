'use strict';
const assert=require('node:assert/strict');
const w=require('../source/onboarding-workflow');
const emp={id:'e1',companyId:'c1',role:'employee'};
const foreman={id:'f1',companyId:'c1',role:'foreman'};
const doc={id:'s1',companyId:'c1',title:'Trenching',revision:'1',type:'SWP',status:'approved',roles:['employee'],approvedBy:'safety'};
const other={...doc,id:'s2',companyId:'c2'};
assert.equal(w.packageFor([doc,other],emp,[]).total,1);
let records=w.submitAcknowledgement([doc],emp,{documentId:'s1',revision:'1',reviewed:true,acknowledgedAt:'2026-11-13T12:00:00Z'},[]);
assert.equal(w.packageFor([doc],emp,records).completed,1);
records=w.submitAcknowledgement([doc],emp,{documentId:'s1',revision:'1',reviewed:true,acknowledgedAt:'2026-11-13T12:00:01Z'},records);
assert.equal(records.length,1);
assert.equal(w.packageFor([{...doc,revision:'2'}],emp,records).completed,0);
assert.throws(()=>w.submitAcknowledgement([{...doc,revision:'2'}],emp,{documentId:'s1',revision:'1',reviewed:true,acknowledgedAt:'2026-11-13T12:00:00Z'},records),/outdated/);
assert.throws(()=>w.submitAcknowledgement([doc],{...emp,companyId:'c2'},{documentId:'s1',revision:'1',reviewed:true,acknowledgedAt:'2026-11-13T12:00:00Z'},[]),/Unassigned/);
assert.throws(()=>w.roleView(foreman,[emp],[doc],records),/not authorized/);
assert.deepEqual(w.roleView({id:'sa',companyId:'c1',role:'safety-admin'},[emp,{...emp,id:'e2',companyId:'c2'}],[doc],records).map(x=>x.employeeId),['e1']);
const flha={id:'h1',companyId:'c1',foremanId:'f1',revision:'4',status:'submitted'};
assert.equal(w.flhaReview(flha,foreman,{status:'approved',reviewedAt:'2026-11-13T12:00:00Z'}).revision,'4');
assert.throws(()=>w.flhaReview(flha,{...foreman,id:'f2'},{status:'approved',reviewedAt:'2026-11-13T12:00:00Z'}),/not assigned/);
assert.throws(()=>w.flhaReview(flha,foreman,{status:'returned',reviewedAt:'2026-11-13T12:00:00Z'}),/return reason/);
console.log('PASS: onboarding packages, revision acknowledgement, role views, FLHA foreman review');
