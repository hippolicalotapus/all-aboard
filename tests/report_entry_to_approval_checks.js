'use strict';
const assert=require('node:assert/strict');
const flow=require('../source/daily-report-lifecycle');
const ctx={companyId:'fictional-co',projectId:'fictional-site',date:'2026-11-14'};
const foreman={id:'foreman-a',role:'foreman',companyId:ctx.companyId,projectId:ctx.projectId};
const entry=(id,kind,sourceId,quantity,status='verified',source='field-entry')=>({...ctx,id,kind,sourceId,quantity,status,source,unit:kind==='time'?'hours':'units'});
const inputs=[entry('hours','time','clock-1',8),entry('production','production','shift-1',12),entry('equipment','equipment','meter-1',4),entry('material','material','ticket-1',20),entry('duplicate','time','clock-1',8),entry('plan','material','flha-1',30,'planned','flha-plan')];
let s=flow.start(inputs,ctx);
assert.equal(s.report.status,'draft');
assert.equal(s.report.entries.length,4);
assert.deepEqual(s.report.exceptions.map(x=>x.reason),['duplicate-source','not-verified-actual']);
assert.throws(()=>flow.action(s,foreman,{type:'approve',actionId:'blocked',expectedRevision:1}),/Unresolved/);
s=flow.action(s,foreman,{type:'exclude',recordId:'duplicate',reason:'Source entered twice',actionId:'remove-duplicate',expectedRevision:1});
s=flow.action(s,foreman,{type:'exclude',recordId:'plan',reason:'Plan is not an actual',actionId:'remove-plan',expectedRevision:2});
assert.equal(s.report.exceptions.length,0);
const retry={type:'exclude',recordId:'plan',reason:'Plan is not an actual',actionId:'remove-plan',expectedRevision:2};
assert.strictEqual(flow.action(s,foreman,retry),s);
assert.throws(()=>flow.action(s,{...foreman,id:'foreman-b'},retry),/Action ID conflict/);
assert.throws(()=>flow.action(s,{...foreman,id:' '},{type:'correct',recordId:'hours',quantity:7,reason:'Verified hours correction',actionId:'missing-actor',expectedRevision:s.revision}),/Actor identity required/);
assert.throws(()=>flow.action(s,{...foreman,role:'employee'},{type:'approve',actionId:'employee',expectedRevision:s.revision}),/access denied/);
assert.throws(()=>flow.action(s,{...foreman,companyId:'other-company'},{type:'approve',actionId:'other-company',expectedRevision:s.revision}),/access denied/);
s=flow.action(s,foreman,{type:'correct',recordId:'hours',quantity:7,reason:'Verified hours correction',actionId:'correct-hours',expectedRevision:s.revision});
assert.equal(s.report.entries.find(x=>x.id==='hours').quantity,7);
assert.equal(s.events.at(-1).oldQuantity,8);
s=flow.action(s,foreman,{type:'approve',actionId:'approve-one',expectedRevision:s.revision});
assert.equal(s.report.status,'foreman-approved');
assert.equal(s.report.approvedBy,'foreman-a');
assert.throws(()=>flow.action(s,foreman,{type:'correct',recordId:'hours',quantity:6,reason:'Cannot change approved',actionId:'late-edit',expectedRevision:s.revision}),/immutable/);
assert.equal(flow.view(s,{role:'accounting',companyId:ctx.companyId,projectIds:[ctx.projectId]}).canEdit,false);
assert.equal(flow.verifyAudit(s),true);
s=flow.action(s,foreman,{type:'reopen',reason:'Reviewed time adjustment',actionId:'reopen-one',expectedRevision:s.revision});
assert.equal(s.report.status,'draft');
s=flow.action(s,foreman,{type:'approve',actionId:'approve-two',expectedRevision:s.revision});
assert.equal(s.report.status,'foreman-approved');
assert.equal(flow.verifyAudit(s),true);
console.log('PASS: fictional enter-once records, report projection, exceptions, actor identity, review, audit and reapproval');
